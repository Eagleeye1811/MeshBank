#!/usr/bin/env python3
"""Generate the mesh NGINX configs from scripts/mesh_topology.py.

Outputs:
* k8s/mesh-sidecar-configs.yaml                 single cluster
* k8s/multicluster/mesh-sidecar-configs.yaml    two clusters (aws/gcp): calls to
  a workload in the other cluster go to the local "<cluster>-gateway" alias
* k8s/multicluster/east-west-gateway.yaml       per-cluster gateway + alias Service

Each meshed pod runs its application on 127.0.0.1:8080 and an NGINX sidecar:

* ``:<public port>`` plaintext. Public API, health checks, NodePort and router
  traffic. Internal endpoints return 403 MTLS_REQUIRED here.
* ``:8443`` mutual TLS. The caller must present a certificate signed by the mesh
  CA *and* its subject CN must be one of this workload's authorized callers
  (403 IDENTITY_NOT_AUTHORIZED otherwise).
* ``127.0.0.1:90xx`` egress, one per upstream. The app sends plaintext to
  loopback; the sidecar opens mTLS to the upstream sidecar with this
  workload's certificate and verifies the upstream's server certificate.
* ``:9102`` stub_status metrics and sidecar health.

The east-west gateway reads only the TLS ClientHello (SNI) and forwards the
encrypted stream to the named service's mTLS port. It never terminates TLS, so
the certificate check and caller authorization still happen in the receiving
sidecar. Only services the other cluster is authorized to call are routable.

Configs contain the placeholder __KUBE_DNS__; containers substitute their
pod's nameserver at start (kind, EKS and GKE all use different addresses).

Run ``--check`` in CI to fail when a committed file is stale.
"""

from __future__ import annotations

import argparse
import re
import sys
import textwrap
from pathlib import Path

from mesh_topology import (
    APP_LOOPBACK,
    CLUSTERS,
    DEPLOYMENTS,
    GATEWAY_NODE_PORT,
    GATEWAY_PORT,
    METRICS_PORT,
    MTLS_PORT,
    MULTI,
    NAMESPACE,
    SINGLE,
    WORKLOADS,
    Deployment,
    exported,
    gateway_alias,
)

K8S = Path(__file__).resolve().parents[1] / "k8s"
CERT_DIR = "/etc/mesh/certs"
KUBE_DNS = "__KUBE_DNS__"  # replaced at container start, see PROXY_ENTRYPOINT
HEADER = (
    "# GENERATED by scripts/generate_mesh_sidecars.py from scripts/mesh_topology.py.\n"
    "# Do not edit by hand: change the topology and regenerate (make mesh-configs).\n"
)


def error_json(code: str, message: str) -> str:
    return f'\'{{"error":{{"code":"{code}","message":"{message}"}}}}\\n\''


MTLS_REQUIRED = error_json(
    "MTLS_REQUIRED", f"Internal endpoints are only served over mTLS on port {MTLS_PORT}"
)


def proxy_to_app(extra: str = "") -> str:
    return f"""proxy_pass http://{APP_LOOPBACK};
                proxy_set_header Host $host;
                proxy_set_header X-Real-IP $remote_addr;
                proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;{extra}"""


def format_nginx(conf: str) -> str:
    """Re-indent by brace depth (the nested f-strings above don't line up)."""
    out, depth, blank = [], 0, False
    for raw in conf.splitlines():
        line = raw.strip()
        if not line:
            if not blank and out and not out[-1].endswith("{"):
                out.append("")
            blank = True
            continue
        blank = False
        quoted = line.startswith("'")  # log_format continuation lines
        if line.startswith("}") and not quoted:
            depth -= 1
            if out and out[-1] == "":
                out.pop()
        out.append("    " * (depth + quoted) + line)
        if line.endswith("{") and not line.endswith("'{'"):
            depth += 1
    if depth != 0:
        raise ValueError("unbalanced braces in generated nginx.conf")
    return "\n".join(out) + "\n"


def egress_target(caller: Deployment, upstream: str, mode: str) -> tuple[str, str]:
    """(address to connect to, how it is reached) for one egress listener."""
    up = WORKLOADS[upstream]
    if mode == MULTI and up.cluster != caller.workload.cluster:
        alias = f"{gateway_alias(up.cluster)}.{NAMESPACE}.svc.cluster.local:{GATEWAY_PORT}"
        return alias, f"via the {up.cluster} east-west gateway"
    return f"{up.fqdn}:{MTLS_PORT}", "in-cluster"


def render(d: Deployment, mode: str) -> str:
    w = d.workload
    proxy_name = f"{w.short}-sidecar" + (f"-{d.track}" if d.track else "")
    track_header = (
        f'\n                add_header X-Mesh-Track "{d.track}" always;' if d.track else ""
    )

    caller_map = "".join(
        f'\n            "~(^|,)CN={re.escape(WORKLOADS[c].fqdn)}(,|$)" "{c}";' for c in w.callers
    )

    if w.public_api:
        public_locations = f"""
            location /internal/ {{
                return 403 {MTLS_REQUIRED};
            }}
{"".join(f'''
            location = {p} {{
                return 403 {MTLS_REQUIRED};
            }}
''' for p in w.internal_paths)}
            location / {{
                {proxy_to_app(track_header)}
            }}"""
    else:
        public_locations = f"""
            # Internal-only service: the public port serves health checks only.
            location = /health {{
                {proxy_to_app(track_header)}
            }}

            location = /ready {{
                {proxy_to_app(track_header)}
            }}

            location / {{
                return 403 {MTLS_REQUIRED};
            }}"""

    egress = "".join(
        f"""
        # Egress to {up} ({egress_target(d, up, mode)[1]}):
        # app -> http://127.0.0.1:{WORKLOADS[up].egress_port} -> mTLS as {w.name}
        server {{
            listen 127.0.0.1:{WORKLOADS[up].egress_port};

            location / {{
                # A variable defers DNS to request time, so the sidecar starts
                # even before the upstream Service exists. SNI and certificate
                # verification always use the target service's own name.
                set $mesh_upstream https://{egress_target(d, up, mode)[0]};
                proxy_pass $mesh_upstream;
                proxy_ssl_certificate {CERT_DIR}/tls.crt;
                proxy_ssl_certificate_key {CERT_DIR}/tls.key;
                proxy_ssl_trusted_certificate {CERT_DIR}/ca.crt;
                proxy_ssl_verify on;
                proxy_ssl_verify_depth 2;
                proxy_ssl_name {WORKLOADS[up].fqdn};
                proxy_ssl_server_name on;
                proxy_ssl_protocols TLSv1.2 TLSv1.3;
                proxy_ssl_session_reuse on;
                proxy_set_header Host {WORKLOADS[up].fqdn};
                proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
            }}
        }}
"""
        for up in w.upstreams
    )

    conf = f"""pid /tmp/nginx.pid;
worker_processes 1;

events {{
    worker_connections 1024;
}}

http {{
    client_body_temp_path /tmp/client_temp;
    proxy_temp_path       /tmp/proxy_temp_path;
    fastcgi_temp_path     /tmp/fastcgi_temp;
    uwsgi_temp_path       /tmp/uwsgi_temp;
    scgi_temp_path        /tmp/scgi_temp;
    default_type application/json;
    server_tokens off;

    resolver {KUBE_DNS} valid=10s ipv6=off;

    # Workload identity: callers allowed on the mTLS port, keyed by the CN of a
    # certificate the mesh CA signed. Empty means "not authorized".
    map $ssl_client_s_dn $mesh_caller {{
        default "";{caller_map}
    }}

    log_format mesh_json escape=json '{{'
      '"time":"$time_iso8601",'
      '"proxy":"{proxy_name}",'
      '"server_port":"$server_port",'
      '"client_ip":"$remote_addr",'
      '"ssl_client_s_dn":"$ssl_client_s_dn",'
      '"ssl_client_verify":"$ssl_client_verify",'
      '"mesh_caller":"$mesh_caller",'
      '"ssl_protocol":"$ssl_protocol",'
      '"ssl_cipher":"$ssl_cipher",'
      '"method":"$request_method",'
      '"uri":"$request_uri",'
      '"status":$status,'
      '"bytes_sent":$bytes_sent,'
      '"request_time":$request_time,'
      '"upstream_addr":"$upstream_addr",'
      '"upstream_response_time":"$upstream_response_time"'
    '}}';

    access_log /dev/stdout mesh_json;
    error_log /dev/stderr warn;

    # Inbound mTLS. A missing or untrusted client certificate fails with 400
    # before any location runs; a trusted but unauthorized identity gets 403.
    server {{
        listen {MTLS_PORT} ssl;
        server_name {w.fqdn} {w.name} localhost;

        ssl_certificate {CERT_DIR}/tls.crt;
        ssl_certificate_key {CERT_DIR}/tls.key;
        ssl_client_certificate {CERT_DIR}/ca.crt;
        ssl_verify_client on;
        ssl_verify_depth 2;
        ssl_protocols TLSv1.2 TLSv1.3;
        ssl_ciphers HIGH:!aNULL:!MD5;
        ssl_prefer_server_ciphers on;

        location / {{
            if ($mesh_caller = "") {{
                return 403 {error_json("IDENTITY_NOT_AUTHORIZED",
                                       f"Caller identity is not authorized for {w.name}")};
            }}
            {proxy_to_app(f'''
                proxy_set_header X-Forwarded-Proto https;
                proxy_set_header X-Mesh-Caller $mesh_caller;{track_header}''')}
        }}
    }}

    # Inbound plaintext (public API, probes, NodePort, router).
    server {{
        listen {w.public_port};
        {public_locations.strip()}
    }}
{egress}
    server {{
        listen {METRICS_PORT};

        location /metrics {{
            default_type text/plain;
            stub_status;
        }}

        location = /health {{
            return 200 '{{"status":"ok","proxy":"{proxy_name}","mtls_port":{MTLS_PORT}}}\\n';
        }}
    }}
}}
"""
    conf = format_nginx(conf)
    return f"""---
apiVersion: v1
kind: ConfigMap
metadata:
  name: {d.config_name}
  namespace: meshbank
  labels:
    meshbank.io/workload: {w.name}
data:
  nginx.conf: |
{textwrap.indent(conf, "    ")}"""


def render_gateway(cluster: str) -> str:
    """East-west gateway for ``cluster`` plus its alias for the other cluster."""
    (other,) = (c for c in CLUSTERS if c != cluster)
    routes = "".join(f"\n        {w.fqdn} {w.fqdn}:{MTLS_PORT};" for w in exported(cluster))
    conf = format_nginx(f"""pid /tmp/nginx.pid;
worker_processes 1;

events {{
    worker_connections 1024;
}}

stream {{
    resolver {KUBE_DNS} valid=10s ipv6=off;

    log_format gateway_json escape=json '{{'
      '"time":"$time_iso8601",'
      '"gateway":"{cluster}",'
      '"client_ip":"$remote_addr",'
      '"sni":"$ssl_preread_server_name",'
      '"upstream":"$upstream_addr",'
      '"status":$status,'
      '"bytes_in":$bytes_received,'
      '"bytes_out":$bytes_sent,'
      '"session_time":$session_time'
    '}}';

    access_log /dev/stdout gateway_json;
    error_log /dev/stderr warn;

    # Routable services: those {other} workloads are authorized to call. Any
    # other server name is sent to a closed port, i.e. refused.
    map $ssl_preread_server_name $mesh_target {{{routes}
        default 127.0.0.1:1;
    }}

    # TLS passthrough: read the ClientHello's SNI, forward the encrypted
    # stream. mTLS is verified end-to-end by the receiving sidecar.
    server {{
        listen {GATEWAY_PORT};
        ssl_preread on;
        proxy_pass $mesh_target;
        proxy_connect_timeout 5s;
    }}
}}
""")
    labels = f"""  labels:
    meshbank.io/cluster: {cluster}"""
    return f"""---
apiVersion: v1
kind: ConfigMap
metadata:
  name: east-west-gateway-config
  namespace: {NAMESPACE}
{labels}
data:
  nginx.conf: |
{textwrap.indent(conf, "    ")}---
apiVersion: apps/v1
kind: Deployment
metadata:
  name: east-west-gateway
  namespace: {NAMESPACE}
{labels}
    app: east-west-gateway
spec:
  replicas: 1
  selector:
    matchLabels:
      app: east-west-gateway
  template:
    metadata:
      labels:
        app: east-west-gateway
        meshbank.io/gateway: "true"
    spec:
      securityContext:
        runAsNonRoot: true
        runAsUser: 10001
        runAsGroup: 10001
      containers:
        - name: gateway
          image: nginx:alpine
          imagePullPolicy: Never
{PROXY_ENTRYPOINT}
          ports:
            - name: tls-passthru
              containerPort: {GATEWAY_PORT}
          volumeMounts:
            - name: config
              mountPath: /etc/mesh/config
              readOnly: true
            - name: tmp
              mountPath: /tmp
          resources:
            requests:
              cpu: 20m
              memory: 32Mi
            limits:
              cpu: 200m
              memory: 128Mi
          readinessProbe:
            tcpSocket:
              port: {GATEWAY_PORT}
            initialDelaySeconds: 3
            periodSeconds: 5
          livenessProbe:
            tcpSocket:
              port: {GATEWAY_PORT}
            initialDelaySeconds: 10
            periodSeconds: 10
          securityContext:
            allowPrivilegeEscalation: false
            capabilities:
              drop: [ALL]
      volumes:
        - name: config
          configMap:
            name: east-west-gateway-config
        - name: tmp
          emptyDir: {{}}
---
# Reached by the {other} cluster on every node at :{GATEWAY_NODE_PORT}.
apiVersion: v1
kind: Service
metadata:
  name: east-west-gateway
  namespace: {NAMESPACE}
{labels}
spec:
  type: NodePort
  selector:
    app: east-west-gateway
  ports:
    - name: tls-passthru
      port: {GATEWAY_PORT}
      targetPort: {GATEWAY_PORT}
      nodePort: {GATEWAY_NODE_PORT}
---
# Alias for the {other} cluster's gateway. No selector: deploy-multicluster.sh
# creates the EndpointSlice with that cluster's node address.
apiVersion: v1
kind: Service
metadata:
  name: {gateway_alias(other)}
  namespace: {NAMESPACE}
{labels}
spec:
  ports:
    - name: tls-passthru
      port: {GATEWAY_PORT}
      protocol: TCP
"""


# Containers mount their config at /etc/mesh/config and start through this, so
# one config works on any cluster: the pod's nameserver *is* the cluster DNS.
PROXY_ENTRYPOINT = """          command:
            - /bin/sh
            - -c
            - >-
              ns=$(awk '/^nameserver/ {print $2; exit}' /etc/resolv.conf)
              && sed "s/__KUBE_DNS__/$ns/g" /etc/mesh/config/nginx.conf > /tmp/nginx.conf
              && exec nginx -c /tmp/nginx.conf -g 'daemon off;'"""


def build() -> dict[Path, str]:
    return {
        K8S / "mesh-sidecar-configs.yaml": HEADER + "".join(render(d, SINGLE) for d in DEPLOYMENTS),
        K8S / "multicluster" / "mesh-sidecar-configs.yaml": HEADER
        + "".join(render(d, MULTI) for d in DEPLOYMENTS),
        K8S / "multicluster" / "east-west-gateway.yaml": HEADER
        + "".join(render_gateway(c) for c in CLUSTERS),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if a file is stale")
    args = parser.parse_args()
    outputs = build()
    if args.check:
        stale = [
            p for p, c in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != c
        ]
        for p in stale:
            print(f"{p} is stale; run make mesh-configs", file=sys.stderr)
        if not stale:
            print("generated mesh configs are up to date")
        return 1 if stale else 0
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"Wrote {path.relative_to(K8S.parent)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
